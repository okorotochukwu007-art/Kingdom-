export function mapCategorySlugToApprovedMain(slug: string, channelType?: string): string {
  // Never alter movie categories
  if (
    slug === 'real-christian-movies' ||
    slug === 'bible-stories' ||
    slug === 'christian-animations' ||
    slug === 'bible-story-cartoons' ||
    channelType === 'movie_studio' ||
    channelType === 'animation_studio'
  ) {
    return slug;
  }
  return LEGACY_TO_MAIN_CATEGORY_MAP[slug]?.mainSlug || 'sermons-teachings';
}

