export function enrichChannelWithMinisterDirectoryProfile(channel: KingdomChannel): KingdomChannel {
  const profile = VERIFIED_MINISTER_PROFILES[channel.youtube_channel_id];
  const mappedDefaultCategory = mapCategorySlugToApprovedMain(
    channel.default_category_slug,
    channel.channel_type
  );
  const mappedSupported = Array.from(
    new Set(
      (channel.supported_categories || [channel.default_category_slug]).map((slug) =>
        mapCategorySlugToApprovedMain(slug, channel.channel_type)
      )
    )
  );

  // Derive clean speaker_name if not explicitly in VERIFIED_MINISTER_PROFILES
  const fallbackSpeakerName = channel.title
    .replace(/\s*\(.*?\)\s*/g, '')
    .replace(/\s+(Main|Official|World|Channel|TV)$/i, '')
    .trim();

  return {
    ...channel,
    speaker_name: channel.speaker_name || profile?.speakerName || fallbackSpeakerName,
    ministry_name: channel.ministry_name || profile?.ministryName || channel.title,
    aliases: Array.from(
      new Set([...(channel.aliases || []), ...(profile?.aliases || []), channel.title, channel.handle])
    ),
    bio: channel.bio || profile?.bio || '',
    is_featured_minister:
      typeof channel.is_featured_minister === 'boolean'
        ? channel.is_featured_minister
        : Boolean(profile?.isFeaturedMinister),
    default_category_slug: mappedDefaultCategory,
    supported_categories: mappedSupported,
  };
}

export const SEED_CHANNELS: KingdomChannel[] = RAW_SEED_CHANNELS.map(
  enrichChannelWithMinisterDirectoryProfile
);


